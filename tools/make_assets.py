"""
make_assets.py — generates src/ui_assets.c from assets/: the TTF fonts as bytes and the
light icons as 8-bit alpha (A8) images. The UI colours the icons itself (green / grey).

Run from the repository root after changing the font or an icon:  python tools/make_assets.py
Needs Pillow (pip install pillow). Only needed on a PC, the result is committed.
"""
import math
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
FONTS = [("exo2_semibold", ROOT / "assets/fonts/Exo2-SemiBoldItalic.ttf"),     # labels, units
         ("exo2_extrabold", ROOT / "assets/fonts/Exo2-ExtraBoldItalic.ttf")]   # numbers
OUT = ROOT / "src/ui_assets.c"

ICON_PX = 56   # final size on screen
SS = 8         # drawn 8x bigger, then shrunk: smooth edges
STROKE = 3.5   # line width, in the 48x48 design grid


def bezier(p0, p1, p2, p3, n=40):
    pts = []
    for k in range(n + 1):
        t = k / n
        u = 1 - t
        pts.append((u**3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t**3 * p3[0],
                    u**3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t**3 * p3[1]))
    return pts


def draw_icon(paint):
    """paint(d, s, w): d = ImageDraw, s(x, y) scales from the 48x48 grid, w = scaled stroke width."""
    size = ICON_PX * SS
    img = Image.new("L", (size, size), 0)
    d = ImageDraw.Draw(img)
    k = size / 48
    paint(d, lambda x, y: (x * k, y * k), int(STROKE * k))
    return img.resize((ICON_PX, ICON_PX), Image.LANCZOS)


def line(d, s, w, *pts):
    d.line([s(*p) for p in pts], fill=255, width=w, joint="curve")
    for p in (pts[0], pts[-1]):   # round caps
        x, y = s(*p)
        d.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=255)


def icon_left(d, s, w):
    d.polygon([s(3, 24), s(21, 7), s(21, 17), s(44, 17), s(44, 31), s(21, 31), s(21, 41)], fill=255)


def icon_right(d, s, w):
    d.polygon([s(45, 24), s(27, 7), s(27, 17), s(4, 17), s(4, 31), s(27, 31), s(27, 41)], fill=255)


def icon_headlight(d, s, w):
    lamp = bezier((27, 9), (39, 9), (44, 17), (44, 24)) + bezier((44, 24), (44, 31), (39, 39), (27, 39))
    line(d, s, w, *lamp, (27, 9))
    for y in (12, 20, 28, 36):          # beams pointing down-left (low beam)
        line(d, s, w, (20, y), (5, y + 4))


def icon_running(d, s, w):
    for cx, sign in ((21, -1), (27, 1)):  # two half lamps, flat sides back to back, round sides outwards
        arc = [(cx + sign * 9 * math.sin(a / 20 * math.pi), 24 - 9 * math.cos(a / 20 * math.pi))
               for a in range(21)]
        line(d, s, w, *arc, (cx, 15))
        x0, x1 = (9, 3) if sign == -1 else (39, 45)
        for y0, y1 in ((17, 14), (24, 24), (31, 34)):
            line(d, s, w, (x0, y0), (x1, y1))


def icon_wiper(d, s, w):
    glass = bezier((5, 38), (9, 13), (39, 13), (43, 38))
    line(d, s, w, *glass, (5, 38))
    line(d, s, w, (24, 38), (13, 21))
    x, y = s(24, 38)
    r = 3 * ICON_PX * SS / 48
    d.ellipse([x - r, y - r, x + r, y + r], fill=255)


ICONS = [("left", icon_left), ("right", icon_right), ("headlight", icon_headlight),
         ("running", icon_running), ("wiper", icon_wiper)]


def c_bytes(data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return "    " + ",\n    ".join(rows)


def main():
    out = ['/* GENERATED by tools/make_assets.py — do not edit by hand. */',
           '#include "ui_assets.h"', '']
    font_bytes = 0
    for name, path in FONTS:
        font = path.read_bytes()
        font_bytes += len(font)
        out += [f"/* {path.name} (SIL Open Font License, see assets/fonts/OFL.txt) */",
                f"const uint8_t ui_font_{name}[] = {{", c_bytes(font), "};",
                f"const size_t ui_font_{name}_size = {len(font)};", ""]
    for name, paint in ICONS:
        px = draw_icon(paint).tobytes()
        out += [f"static const uint8_t icon_{name}_map[] = {{", c_bytes(px), "};",
                f"const lv_image_dsc_t ui_icon_{name} = {{",
                "    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8,",
                f"               .w = {ICON_PX}, .h = {ICON_PX}, .stride = {ICON_PX}}},",
                f"    .data_size = sizeof(icon_{name}_map),",
                f"    .data = icon_{name}_map,", "};", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({font_bytes} font bytes, {len(ICONS)} icons)")


if __name__ == "__main__":
    main()
